"""Second-pass question verification adapter to prevent incorrect answers."""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

from pydantic import BaseModel, Field

from sahayak.core.observability.metrics import (
    QUESTION_VERIFICATION_ATTEMPTS_TOTAL,
    QUESTION_VERIFICATION_REJECTIONS_TOTAL,
)
from sahayak.modules.academics.models import Question
from sahayak.shared.llm.ports import LLMClient

logger = logging.getLogger(__name__)

VERIFY_PROMPT_VERSION = "v1"
VERIFY_PROMPT_PATH = Path("prompts/quiz_verify_v1.md")


class RawVerificationOutput(BaseModel):
    """Structured JSON output expected from the independent verification pass."""

    solved_key: str = Field(
        description="The key of the verified correct option ('A', 'B', 'C', or 'D')"
    )
    confidence: str = Field(default="high", description="Confidence level: high, medium, or low")
    reasoning: str = Field(default="", description="Factual justification for the selected option")


@dataclass(frozen=True)
class VerificationResult:
    """Outcome of an independent verification check."""

    is_verified: bool
    generator_key: str
    verifier_key: str | None
    reason: str
    confidence: str = "high"


class QuestionVerifier:
    """Adapter executing independent second-pass verification for candidate questions."""

    def __init__(
        self,
        llm_client: LLMClient,
        prompt_path: Path = VERIFY_PROMPT_PATH,
    ) -> None:
        self._llm = llm_client
        self._prompt_path = prompt_path
        self._prompt_template: str | None = None

    def _load_prompt_template(self) -> str:
        if self._prompt_template is None:
            if not self._prompt_path.is_file():
                msg = f"Missing verification prompt template at {self._prompt_path}"
                raise FileNotFoundError(msg)
            self._prompt_template = self._prompt_path.read_text(encoding="utf-8")
        return self._prompt_template

    async def verify_question(
        self,
        question: Question,
        topic_name: str,
        grounding_block: str = "",
        model: str | None = None,
    ) -> VerificationResult:
        """Independently solve the candidate question and check for answer agreement.

        Args:
            question: The candidate question generated by the primary pipeline.
            topic_name: Human-readable topic display name.
            grounding_block: Delimited factual grounding material (if available).
            model: Optional secondary model override.

        Returns:
            VerificationResult indicating whether the generator and verifier agreed.
        """
        template = self._load_prompt_template()
        options = question.options or {}

        prompt = template.format(
            topic=topic_name,
            grounding_block=grounding_block or "None provided.",
            stem=question.stem,
            option_A=options.get("A", ""),
            option_B=options.get("B", ""),
            option_C=options.get("C", ""),
            option_D=options.get("D", ""),
        )

        try:
            response = await self._llm.generate_json(
                prompt=prompt,
                schema=RawVerificationOutput,
                temperature=0.1,
                model=model,
            )

            raw_output: RawVerificationOutput
            if isinstance(response.parsed, RawVerificationOutput):
                raw_output = response.parsed
            elif isinstance(response.parsed, dict):
                raw_output = RawVerificationOutput.model_validate(response.parsed)
            else:
                raw_output = RawVerificationOutput.model_validate_json(response.content)

            verifier_key = raw_output.solved_key.strip().upper()
            generator_key = question.correct_key.strip().upper()

            if verifier_key == generator_key:
                QUESTION_VERIFICATION_ATTEMPTS_TOTAL.labels(topic_name, "verified").inc()
                return VerificationResult(
                    is_verified=True,
                    generator_key=generator_key,
                    verifier_key=verifier_key,
                    reason="Verifier and generator agree on correct option.",
                    confidence=raw_output.confidence,
                )

            # Disagreement detected
            QUESTION_VERIFICATION_ATTEMPTS_TOTAL.labels(topic_name, "disagreement").inc()
            QUESTION_VERIFICATION_REJECTIONS_TOTAL.labels(topic_name, "answer_disagreement").inc()
            logger.info(
                "Verification disagreement on '%s': generator=%s, verifier=%s (reason: %s)",
                question.stem[:60],
                generator_key,
                verifier_key,
                raw_output.reasoning,
            )
            return VerificationResult(
                is_verified=False,
                generator_key=generator_key,
                verifier_key=verifier_key,
                reason=(
                    f"Answer disagreement: generator chose {generator_key}, "
                    f"verifier chose {verifier_key}."
                ),
                confidence=raw_output.confidence,
            )

        except Exception as exc:
            QUESTION_VERIFICATION_ATTEMPTS_TOTAL.labels(topic_name, "error").inc()
            QUESTION_VERIFICATION_REJECTIONS_TOTAL.labels(topic_name, "verification_error").inc()
            logger.warning(
                "Verification call failed for question '%s': %s", question.stem[:60], exc
            )
            return VerificationResult(
                is_verified=False,
                generator_key=question.correct_key,
                verifier_key=None,
                reason=f"Verification failure: {exc}",
                confidence="low",
            )
